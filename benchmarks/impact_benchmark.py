"""Impact benchmark: ThreatLens vs a typical manual threat-modeling engagement.

Measures (offline, deterministic mode, so anyone can reproduce with zero keys):
  * wall-clock time-to-threat-model (median of N runs)
  * findings by severity, STRIDE / OWASP Top 10 coverage
  * recall against an author-defined expert checklist (benchmarks/expected/*.yaml)
and compares against a stated manual-engagement baseline. Writes docs/impact.md.

Usage:  python benchmarks/impact_benchmark.py [--runs 20]
"""
from __future__ import annotations

import argparse
import statistics
import sys
import tempfile
import time
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from threatlens.agent import run_threat_model  # noqa: E402
from threatlens.report import summary_stats  # noqa: E402

# ---------------------------------------------------------------- baseline assumptions (edit to taste)
BASELINE = {
    "consultant_days_low": 3, "consultant_days_high": 5,     # workshop + DFD + STRIDE + report
    "hours_per_day": 8,
    "day_rate_usd_low": 500, "day_rate_usd_high": 900,       # assumed senior AppSec consultant day rate, Egypt/KSA SME market
    "lead_time_days_low": 7, "lead_time_days_high": 21,      # assumed time to procure & schedule a consultant
    "review_hours_low": 2, "review_hours_high": 4,           # assumed human review of ThreatLens output (recommended)
}


def checklist_recall(state, expected: dict) -> tuple[int, int, list[str]]:
    hit, missed = 0, []
    for item in expected["items"]:
        cwes, target = set(item["cwe"]), item.get("target")
        flow_targets = {f.id: f.target for f in state.arch.flows}
        ok = any(cwes & set(f.cwe) and (not target or target in (f.target, flow_targets.get(f.target)))
                 for f in state.findings)
        hit += ok
        if not ok:
            missed.append(item["threat"] + (f" — {item['note']}" if item.get("note") else ""))
    return hit, len(expected["items"]), missed


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", type=int, default=20)
    ap.add_argument("--out", default=str(ROOT / "docs" / "impact.md"))
    args = ap.parse_args(argv)
    rows = []
    for exp_file in sorted((ROOT / "benchmarks" / "expected").glob("*.yaml")):
        exp = yaml.safe_load(exp_file.read_text())
        inp = ROOT / "examples" / exp["system"]
        oa = str(ROOT / "examples" / exp["openapi"]) if exp.get("openapi") else None
        times = []
        for _ in range(args.runs):
            with tempfile.TemporaryDirectory() as d:
                t = time.perf_counter()
                state, _ = run_threat_model(str(inp), openapi=oa, output_dir=d, offline=True)
                times.append(time.perf_counter() - t)
        s = summary_stats(state)
        hit, total, missed = checklist_recall(state, exp)
        rows.append({"system": s["system"], "file": exp["system"], "median_s": statistics.median(times),
                     "max_s": max(times), "findings": s["findings"], "sev": s["by_severity"],
                     "stride": sum(1 for v in s["by_stride"].values() if v), "owasp": len(s["owasp_categories"]),
                     "cwes": len(s["unique_cwes"]), "actions": s["remediation_actions"], "effort": s["effort_days"],
                     "hit": hit, "total": total, "missed": missed,
                     "tools": sum(1 for t in state.trace if t.get("kind") == "tool")})
    write_report(rows, args)
    for r in rows:
        print(f"{r['system']:35s} {r['median_s']*1000:7.1f} ms  findings={r['findings']:3d}  "
              f"checklist recall={r['hit']}/{r['total']}  OWASP={r['owasp']}/10")
    print(f"wrote {args.out}")
    return 0


def write_report(rows, args):
    b = BASELINE
    man_h_lo, man_h_hi = b["consultant_days_low"] * b["hours_per_day"], b["consultant_days_high"] * b["hours_per_day"]
    cost_lo, cost_hi = b["consultant_days_low"] * b["day_rate_usd_low"], b["consultant_days_high"] * b["day_rate_usd_high"]
    rev_lo, rev_hi = b["review_hours_low"], b["review_hours_high"]
    review_cost_lo = rev_lo / b["hours_per_day"] * b["day_rate_usd_low"]
    review_cost_hi = rev_hi / b["hours_per_day"] * b["day_rate_usd_high"]
    total_hit = sum(r["hit"] for r in rows)
    total_items = sum(r["total"] for r in rows)
    med_all = statistics.median(r["median_s"] for r in rows)
    L = ["# Measured business impact", "",
         f"*Generated by `python benchmarks/impact_benchmark.py --runs {args.runs}` (offline deterministic mode, no API key).*", "",
         "## Headline", "",
         f"- **Time to a first full threat model:** ~{med_all*1000:.0f} ms of agent time (median across examples) vs "
         f"**{man_h_lo}-{man_h_hi} consultant hours** ({b['consultant_days_low']}-{b['consultant_days_high']} days) for a manual engagement.",
         f"- **Realistic end-to-end effort with expert review:** {rev_lo}-{rev_hi} h vs {man_h_lo}-{man_h_hi} h "
         f"→ **{(1 - rev_hi / man_h_lo) * 100:.0f}-{(1 - rev_lo / man_h_hi) * 100:.0f}% less security-expert time.**",
         f"- **Cost per threat model:** ~USD {review_cost_lo:,.0f}-{review_cost_hi:,.0f} (review time only; offline mode has no API cost) "
         f"vs **USD {cost_lo:,}-{cost_hi:,}** for the consultant engagement.",
         f"- **Lead time:** minutes instead of {b['lead_time_days_low']}-{b['lead_time_days_high']} days to procure and schedule a consultant; "
         "the model can be re-run on every architecture change at no extra cost.",
         f"- **Coverage:** {total_hit}/{total_items} ({total_hit / total_items * 100:.0f}%) of the expert-checklist threats found across the three examples.", "",
         "## Per-example results", "",
         "| Example | Agent time (median / max) | Tool calls | Findings (C/H/M/L) | STRIDE cats | OWASP Top 10 cats | Unique CWEs | Fix actions | Fix effort | Expert-checklist recall |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        sv = r["sev"]
        L.append(f"| {r['system']} (`{r['file']}`) | {r['median_s']*1000:.1f} ms / {r['max_s']*1000:.1f} ms | {r['tools']} | "
                 f"{r['findings']} ({sv['Critical']}/{sv['High']}/{sv['Medium']}/{sv['Low']}) | {r['stride']}/6 | {r['owasp']}/10 | "
                 f"{r['cwes']} | {r['actions']} | {r['effort']} dev-days | {r['hit']}/{r['total']} |")
    L += ["", "### Checklist items not found", ""]
    any_missed = False
    for r in rows:
        for m in r["missed"]:
            any_missed = True
            L.append(f"- **{r['system']}**: {m}")
    if not any_missed:
        L.append("- None.")
    L += ["", "## Baseline assumptions (state them, then challenge them)", "",
          "| Assumption | Value | Basis |", "|---|---|---|",
          f"| Manual engagement length | {b['consultant_days_low']}-{b['consultant_days_high']} consultant-days | Typical scope for an SME web/mobile app: kickoff workshop, DFD, STRIDE session, write-up (author's consulting experience). |",
          f"| Consultant day rate | USD {b['day_rate_usd_low']}-{b['day_rate_usd_high']} | Assumed range for a senior AppSec consultant serving Egypt/KSA SMEs; not a market survey. |",
          f"| Procurement & scheduling lead time | {b['lead_time_days_low']}-{b['lead_time_days_high']} calendar days | Assumption. |",
          f"| Human review of ThreatLens output | {rev_lo}-{rev_hi} hours | Recommended: an engineer/consultant validates findings and closes those with existing controls. |",
          "| Offline-mode API cost | USD 0 | Runs locally on the built-in knowledge base. LLM mode adds the provider's token cost. |", "",
          "## Method & caveats", "",
          "- Timing is wall-clock for the full agent loop (parse → inventory → STRIDE → flows → API → map → score → reflect → plan → diagram → report files), "
          f"median of {args.runs} runs per example on the build machine. LLM mode is slower (seconds to minutes, depending on provider and model).",
          "- The expert checklist (`benchmarks/expected/*.yaml`) was written by the author before measuring; a checklist item counts as found when a finding "
          "carries one of its CWE ids on the expected target. It is **not** an independent ground truth. Treat recall as a sanity check, not a certification.",
          "- Finding counts are not quality on their own: the knowledge base is deliberately conservative (undocumented controls are treated as absent), so "
          "some findings will be closed during review with evidence.",
          "- ThreatLens replaces the *documentation and enumeration* part of a threat-modeling engagement; it does not replace penetration testing or a "
          "consultant's judgment on business-specific abuse cases.", ""]
    Path(args.out).write_text("\n".join(L), encoding="utf-8")


if __name__ == "__main__":
    raise SystemExit(main())
