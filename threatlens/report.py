"""Markdown + HTML + JSON report rendering."""
from __future__ import annotations

import datetime as dt
import html
import json
import re
from collections import Counter
from pathlib import Path

from . import __version__
from .models import COMPONENT_TYPES, DATA_LABELS, STRIDE, ZONE_LABELS

SEV_ORDER = ["Critical", "High", "Medium", "Low"]
SEV_COLOR = {"Critical": "#c0392b", "High": "#e67e22", "Medium": "#c9a400", "Low": "#27ae60"}


def slugify(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", s.lower()).strip("_")[:60] or "report"


def summary_stats(state) -> dict:
    sev = Counter(f.severity for f in state.findings)
    return {
        "system": state.arch.name,
        "components": len(state.arch.components),
        "flows": len(state.arch.flows),
        "endpoints": len(state.arch.endpoints),
        "boundary_crossings": len(state.inventory["boundary_crossings"]) if state.inventory else 0,
        "findings": len(state.findings),
        "by_severity": {s: sev.get(s, 0) for s in SEV_ORDER},
        "by_stride": {v: sum(1 for f in state.findings if f.stride == k) for k, v in STRIDE.items()},
        "owasp_categories": sorted({c for f in state.findings for c in f.owasp_top10}),
        "unique_cwes": sorted({c for f in state.findings for c in f.cwe}, key=lambda x: int(x.split("-")[1]) if x.split("-")[-1].isdigit() else 0),
        "remediation_actions": len(state.plan),
        "effort_days": round(sum(i.effort_days for i in state.plan), 1),
        "effort_now_days": round(sum(i.effort_days for i in state.plan if i.phase.startswith("Now")), 1),
        "mode": state.mode,
    }


def _name(state, target: str) -> str:
    c = state.arch.component(target)
    if c:
        return c.name
    f = next((x for x in state.arch.flows if x.id == target), None)
    if f:
        s, t = state.arch.component(f.source), state.arch.component(f.target)
        return f"{f.id}: {s.name if s else f.source} → {t.name if t else f.target}"
    return "System-wide" if target == "system" else target


def executive_summary(state) -> str:
    s = summary_stats(state)
    crit, high = s["by_severity"]["Critical"], s["by_severity"]["High"]
    top = [f for f in state.findings[:3]]
    now = [i for i in state.plan if i.phase.startswith("Now")]
    txt = (f"ThreatLens analysed **{s['components']} components** and **{s['flows']} data flows** "
           f"({s['boundary_crossings']} crossing trust boundaries) of *{s['system']}* and identified "
           f"**{s['findings']} threats**: {crit} Critical, {high} High, {s['by_severity']['Medium']} Medium, "
           f"{s['by_severity']['Low']} Low, covering {len(s['owasp_categories'])} of the 10 OWASP Top 10 2021 categories. ")
    if top:
        txt += "The highest risks are " + "; ".join(f"**{f.title}** (risk {f.risk}/25)" for f in top) + ". "
    if now:
        txt += (f"Doing the **{len(now)} 'Now' actions** (~{round(sum(i.effort_days for i in now), 1)} developer-days) "
                f"removes the most risk per day of effort; the full plan is ~{s['effort_days']} developer-days.")
    return txt


# ---------------------------------------------------------------------------- Markdown
def render_markdown(state) -> str:
    a, s = state.arch, summary_stats(state)
    now = dt.datetime.now().strftime("%Y-%m-%d %H:%M")
    L = [f"# Threat Model Report — {a.name}", "",
         f"*Generated by ThreatLens v{__version__} on {now} · mode: `{state.mode}` · methodology: STRIDE + OWASP Top 10 2021 / ASVS 4.0.3 / CWE*", ""]
    if a.description:
        L += ["> " + a.description.strip().replace("\n", "\n> "), ""]
    L += ["## 1. Executive summary", "", executive_summary(state), "",
          "| Critical | High | Medium | Low | Total | Remediation effort |", "|---|---|---|---|---|---|",
          f"| {s['by_severity']['Critical']} | {s['by_severity']['High']} | {s['by_severity']['Medium']} | "
          f"{s['by_severity']['Low']} | {s['findings']} | {s['effort_days']} dev-days ({s['effort_now_days']} urgent) |", ""]
    meta = [("Industry", a.industry), ("Region", a.region), ("Users", a.users),
            ("Compliance context", ", ".join(a.compliance))]
    meta = [m for m in meta if m[1]]
    if meta:
        L += ["| Context | |", "|---|---|"] + [f"| {k} | {v} |" for k, v in meta] + [""]

    # inventory
    L += ["## 2. Asset & data-flow inventory", "", "### 2.1 Components", "",
          "| ID | Component | Type | Trust zone | Data | Auth | Internet-facing | Documented controls |",
          "|---|---|---|---|---|---|---|---|"]
    for c in a.components:
        L.append(f"| `{c.id}` | {c.name}{' ('+c.tech+')' if c.tech else ''} | {COMPONENT_TYPES.get(c.type, c.type)} | "
                 f"{c.zone} | {', '.join(DATA_LABELS.get(d, d) for d in c.data) or '—'} | {c.auth} | "
                 f"{'yes' if c.internet_facing else 'no'} | {', '.join(c.controls) or '—'} |")
    L += ["", "### 2.2 Data flows", "", "| ID | From → To | Protocol | Data | Auth | Crosses boundary |", "|---|---|---|---|---|---|"]
    cross = {x["flow"]: x["boundary"] for x in state.inventory["boundary_crossings"]}
    for f in a.flows:
        L.append(f"| {f.id} | {_name(state, f.source)} → {_name(state, f.target)} | {f.protocol.upper()} | "
                 f"{', '.join(f.data) or '—'} | {f.auth} | {cross.get(f.id, '—')} |")
    L += ["", "### 2.3 Trust boundaries", ""]
    for z in state.inventory["trust_zones"]:
        L.append(f"- **{z['label']}**: " + ", ".join(_name(state, m) for m in z["members"]))
    if state.inventory["crown_jewels"]:
        L.append("- **Crown-jewel data stores**: " + ", ".join(_name(state, m) for m in state.inventory["crown_jewels"]))
    if a.endpoints:
        L += ["", f"### 2.4 API surface (OpenAPI)", "", f"{len(a.endpoints)} operations analysed; "
              f"{sum(1 for e in a.endpoints if not e.secured)} declare no security scheme."]
    L += ["", "## 3. Data-flow diagram", "", "Dashed arrows = unencrypted transport. Red/orange/yellow nodes = worst open Critical/High/Medium risk.", "",
          "```mermaid", state.diagram, "```", ""]

    # findings
    L += ["## 4. Findings (risk-ranked)", "",
          "| ID | Severity | Risk (L×I) | STRIDE | Threat | Target | OWASP Top 10 | CWE |", "|---|---|---|---|---|---|---|---|"]
    for f in state.findings:
        L.append(f"| {f.id} | **{f.severity}** | {f.risk} ({f.likelihood}×{f.impact}) | {STRIDE[f.stride]} | {f.title} | "
                 f"{_name(state, f.target)} | {', '.join(x.split(' ')[0] for x in f.owasp_top10)} | {', '.join(f.cwe)} |")
    L += ["", "### 4.1 Finding details", ""]
    from .kb import MITIGATIONS
    for f in state.findings:
        L += [f"#### {f.id} — {f.title}", "",
              f"- **Severity:** {f.severity} (likelihood {f.likelihood}/5 × impact {f.impact}/5 = {f.risk}/25)",
              f"- **STRIDE:** {STRIDE[f.stride]} · **Target:** {_name(state, f.target)}",
              f"- **OWASP Top 10 2021:** {'; '.join(f.owasp_top10)}",
              f"- **OWASP ASVS 4.0.3:** {'; '.join(f.asvs)}",
              f"- **CWE:** {', '.join(f.cwe) or '—'}",
              f"- **Description:** {f.description}",
              f"- **Evidence / basis:** `{f.evidence}`" + (" *(LLM-proposed)*" if f.source == "llm" else ""),
              "- **Mitigation:** " + " ".join(MITIGATIONS.get(m, {}).get("title", m) + "." for m in f.mitigations), ""]

    # plan
    L += ["## 5. Prioritised remediation plan", "",
          "Ordered by phase, then by the highest risk each action closes, then by risk removed per developer-day. Effort assumes a small (2-5 developer) SME team.", "",
          "| # | Phase | Action | Owner | Effort (dev-days) | Fixes | Risk points removed |", "|---|---|---|---|---|---|---|"]
    for i in state.plan:
        L.append(f"| {i.priority} | {i.phase} | **{i.title}** — {i.detail} | {i.owner} | {i.effort_days:g} | "
                 f"{', '.join(i.findings)} | {i.risk_reduced} |")
    phases = {}
    for i in state.plan:
        phases[i.phase] = phases.get(i.phase, 0) + i.effort_days
    L += ["", "**Effort by phase:** " + " · ".join(f"{p}: {v:g} dev-days" for p, v in phases.items()), ""]

    # coverage
    L += ["## 6. Coverage", "", "| STRIDE category | Findings |", "|---|---|"]
    L += [f"| {k} | {v} |" for k, v in s["by_stride"].items()]
    L += ["", "**OWASP Top 10 2021 categories hit:** " + (", ".join(s["owasp_categories"]) or "—"), "",
          "**CWE ids referenced:** " + (", ".join(s["unique_cwes"]) or "—"), ""]

    # assumptions & agent
    notes = list(a.assumptions) + [n for r in state.reflections for n in r["notes"]]
    L += ["## 7. Assumptions, limitations & reviewer notes", ""]
    L += [f"- {n}" for n in dict.fromkeys(notes)] or ["- None."]
    L += ["- Controls not listed in the input are treated as absent; findings for controls that already exist can be closed with evidence.",
          "- This is a design-level threat model, not a penetration test. Validate Critical/High items with testing.", ""]
    L += ["## 8. Agent trace", "", "<details><summary>How the agent reached these results (plan → tools → reflect)</summary>", "",
          "| Step | Actor | Tool / action | Reasoning | Result |", "|---|---|---|---|---|"]
    for t in state.trace:
        if t.get("kind") == "tool":
            L.append(f"| {t['step']} | {t.get('actor')} | `{t['tool']}`{('(' + ', '.join(f'{k}={v}' for k, v in t['args'].items()) + ')') if t.get('args') else ''} | "
                     f"{t.get('thought','').replace('|','/')[:120]} | `{str(t.get('result','')).replace('|','/')[:110]}` |")
        elif t.get("kind") in ("plan", "note"):
            L.append(f"| {t['step']} | agent | {t['kind']} | {t.get('thought','')[:200]} | |")
    L += ["", "</details>", "", "---", "*ThreatLens — AI threat modeling for SMEs. Author: Ahmed Alaa Eldin. MIT License.*", ""]
    return "\n".join(L)


# ---------------------------------------------------------------------------- HTML
def _md_inline(s: str) -> str:
    s = html.escape(s)
    s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
    s = re.sub(r"\*(.+?)\*", r"<em>\1</em>", s)
    s = re.sub(r"`(.+?)`", r"<code>\1</code>", s)
    return s


