def to_json(state) -> dict:
    return {
        "tool": "ThreatLens", "version": __version__, "mode": state.mode,
        "summary": summary_stats(state),
        "inventory": state.inventory,
        "findings": [f.to_dict() for f in state.findings],
        "remediation_plan": [i.__dict__ for i in state.plan],
        "diagram_mermaid": state.diagram,
        "reflections": state.reflections,
        "trace": state.trace,
    }


def write_reports(state, output_dir: str) -> dict:
    out = Path(output_dir)
    out.mkdir(parents=True, exist_ok=True)
    base = slugify(state.arch.name)
    paths = {"markdown": out / f"{base}.md", "html": out / f"{base}.html", "json": out / f"{base}.json", "mermaid": out / f"{base}.mmd"}
    paths["markdown"].write_text(render_markdown(state), encoding="utf-8")
    paths["html"].write_text(render_html(state), encoding="utf-8")
    paths["mermaid"].write_text(state.diagram + "\n", encoding="utf-8")
    paths["json"].write_text(json.dumps(to_json(state), indent=2, default=str, ensure_ascii=False), encoding="utf-8")
    return {k: str(v) for k, v in paths.items()}
